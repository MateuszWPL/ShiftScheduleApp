import {
  Injectable,
  ForbiddenException,
  BadRequestException,
  Logger,
} from '@nestjs/common';
import { PrismaService } from '../prisma/prisma.service';
import { EmailService } from '../email/email.service';
import { MembershipStatus, Role } from '@prisma/client';
import { UpdateTeamSettingsDto, UpdateTeamNameDto, UpdateBusinessHoursDto } from './dto/update-team-settings.dto';
import { nanoid } from 'nanoid';

@Injectable()
export class TeamSettingsService {
  private readonly logger = new Logger(TeamSettingsService.name);

  constructor(
    private readonly prisma: PrismaService,
    private readonly emailService: EmailService,
  ) {}

  /** Get team settings (auto-create if missing) */
  async getSettings(userId: string) {
    const membership = await this.requireAdmin(userId);

    const team = await this.prisma.team.findUnique({
      where: { id: membership.teamId },
      include: { settings: true },
    });

    if (!team) throw new ForbiddenException('Zespół nie znaleziony');

    // Auto-create settings if not yet existing
    let settings = team.settings;
    if (!settings) {
      settings = await this.prisma.teamSettings.create({
        data: { teamId: team.id },
      });
    }

    return {
      team: {
        id: team.id,
        name: team.name,
        inviteCode: team.inviteCode,
        createdAt: team.createdAt.toISOString(),
      },
      settings: {
        companyName: settings.companyName,
        logoUrl: settings.logoUrl,
        defaultOpenHour: settings.defaultOpenHour,
        defaultCloseHour: settings.defaultCloseHour,
        minShiftDurationMin: settings.minShiftDurationMin,
        maxShiftDurationMin: settings.maxShiftDurationMin,
        notifyShiftAssigned: settings.notifyShiftAssigned,
        notifyShiftPublished: settings.notifyShiftPublished,
        notifyMarketplace: settings.notifyMarketplace,
        notifyAnnouncements: settings.notifyAnnouncements,
      },
    };
  }

  /** Update team settings */
  async updateSettings(userId: string, dto: UpdateTeamSettingsDto) {
    const membership = await this.requireAdmin(userId);

    // Ensure settings row exists
    await this.prisma.teamSettings.upsert({
      where: { teamId: membership.teamId },
      create: { teamId: membership.teamId, ...dto },
      update: dto,
    });

    this.logger.log(`Team settings updated by ${userId} for team ${membership.teamId}`);

    return this.getSettings(userId);
  }

  /** Update team name */
  async updateTeamName(userId: string, dto: UpdateTeamNameDto) {
    const membership = await this.requireAdmin(userId);

    await this.prisma.team.update({
      where: { id: membership.teamId },
      data: { name: dto.name },
    });

    this.logger.log(`Team name updated to "${dto.name}" by ${userId}`);

    return this.getSettings(userId);
  }

  /** Regenerate invite code (OWNER only) */
  async regenerateInviteCode(userId: string) {
    const membership = await this.requireAdmin(userId);

    if (membership.role !== Role.OWNER) {
      throw new ForbiddenException('Tylko właściciel może regenerować kod zaproszenia');
    }

    const newCode = nanoid(12);

    await this.prisma.team.update({
      where: { id: membership.teamId },
      data: { inviteCode: newCode },
    });

    this.logger.log(`Invite code regenerated by ${userId} for team ${membership.teamId}`);

    return { inviteCode: newCode };
  }

  async getBusinessHours(userId: string) {
    const membership = await this.requireAdmin(userId);

    const hours = await this.prisma.businessHours.findMany({
      where: { teamId: membership.teamId },
      orderBy: { dayOfWeek: 'asc' },
    });

    if (hours.length === 0) {
      return this.getDefaultBusinessHours();
    }

    return hours.map((h) => ({
      dayOfWeek: h.dayOfWeek,
      isOpen: h.isOpen,
      openTime: h.openTime,
      closeTime: h.closeTime,
    }));
  }

  async updateBusinessHours(userId: string, dto: UpdateBusinessHoursDto) {
    const membership = await this.requireAdmin(userId);
    const teamId = membership.teamId;

    await this.prisma.$transaction(
      dto.days.map((day) =>
        this.prisma.businessHours.upsert({
          where: { teamId_dayOfWeek: { teamId, dayOfWeek: day.dayOfWeek } },
          create: {
            teamId,
            dayOfWeek: day.dayOfWeek,
            isOpen: day.isOpen,
            openTime: day.openTime,
            closeTime: day.closeTime,
          },
          update: {
            isOpen: day.isOpen,
            openTime: day.openTime,
            closeTime: day.closeTime,
          },
        }),
      ),
    );

    this.logger.log(`Business hours updated by ${userId} for team ${teamId}`);
    return this.getBusinessHours(userId);
  }

  async completeOnboarding(userId: string) {
    const membership = await this.requireAdmin(userId);

    await this.prisma.team.update({
      where: { id: membership.teamId },
      data: { onboardingCompleted: true },
    });

    this.logger.log(`Onboarding completed by ${userId} for team ${membership.teamId}`);
    return { success: true };
  }

  async inviteByEmail(userId: string, emails: string[]) {
    const membership = await this.requireAdmin(userId);

    const team = await this.prisma.team.findUnique({
      where: { id: membership.teamId },
    });
    if (!team) throw new ForbiddenException('Zespół nie znaleziony');

    const user = await this.prisma.user.findUnique({
      where: { id: userId },
      select: { name: true },
    });

    const validEmails = emails
      .map((e) => e.trim().toLowerCase())
      .filter((e) => /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(e));

    if (validEmails.length === 0) {
      throw new BadRequestException('Brak prawidłowych adresów email');
    }

    const sent: string[] = [];
    for (const email of validEmails) {
      try {
        await this.emailService.sendTeamInvitationEmail(
          email,
          user?.name || 'Manager',
          team.name,
          team.inviteCode,
        );
        sent.push(email);
      } catch (error) {
        this.logger.error(`Failed to send invite to ${email}: ${error?.message}`);
      }
    }

    this.logger.log(`Invitations sent by ${userId}: ${sent.length}/${validEmails.length}`);
    return { sent, total: validEmails.length };
  }

  private getDefaultBusinessHours() {
    const DAYS = ['Poniedziałek', 'Wtorek', 'Środa', 'Czwartek', 'Piątek', 'Sobota', 'Niedziela'];
    return DAYS.map((_, i) => ({
      dayOfWeek: i,
      isOpen: i < 5,
      openTime: '08:00',
      closeTime: '22:00',
    }));
  }

  private async requireAdmin(userId: string) {
    const membership = await this.prisma.teamMembership.findFirst({
      where: { userId, status: MembershipStatus.ACTIVE },
    });

    if (!membership) throw new ForbiddenException('Brak aktywnego zespołu');

    if (
      membership.role !== Role.OWNER &&
      membership.role !== Role.MANAGER
    ) {
      throw new ForbiddenException('Tylko właściciel lub menedżer ma dostęp do ustawień');
    }

    return membership;
  }
}
